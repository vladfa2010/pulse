/**
 * Регрессионные проверки числового вето и рубрик-чёрного списка
 * кластеризации (ТЗ-95, задача 4 — замена неработающего jest-теста
 * src/tests/clusteringVeto.test.ts: раннера jest в репо нет).
 *
 * Что покрывает:
 *   1. numericVeto — боевой кейс ПВО (85 vs 516 дронов, sim 0.944),
 *      годы не значимы, одиночные цифры не значимы, одинаковые числа
 *      не ветируют, вето не срабатывает при отсутствии чисел у одной стороны;
 *   2. significantNumbers — длина >= 2, годы исключены;
 *   3. isRubricTitle — дайджест после обрезки эмодзи, обычный заголовок
 *      не рубрика.
 *
 * Без БД: проверяемые функции вынесены в dist/services/clusteringRules.js
 * (чистые, без пула соединений).
 *
 * Запуск: npm run verify:clusteringVeto (предварительно npm run build)
 */

const path = require('path');
const distDir = path.join(__dirname, '..', 'dist');

const {
  significantNumbers,
  numericVeto,
  isRubricTitle,
} = require(path.join(distDir, 'services', 'clusteringRules.js'));

let passed = 0;
let failed = 0;
const failures = [];

function check(name, cond) {
  if (cond) {
    passed++;
    console.log(`  ✓ ${name}`);
  } else {
    failed++;
    failures.push(name);
    console.log(`  ✗ ${name}`);
  }
}

// ═══════════════════════════════════════════════════════════════════════════
// 1. numericVeto
// ═══════════════════════════════════════════════════════════════════════════
console.log('\n[numericVeto]');
check(
  'боевой кейс ПВО: «Сбито 85 дронов» ≠ «Сбито 516 дронов» (sim 0.944)',
  numericVeto('Сводка ПВО: сбито 85 дронов над Ростовской областью', 'Сводка ПВО: сбито 516 дронов над Ростовской областью') === true
);
check(
  'годы не значимы: «…в 2025 году» vs «…в 2026 году» — вето НЕ по годам',
  numericVeto('ЦБ решил по ставке в 2025 году', 'ЦБ решил по ставке в 2026 году') === false
);
check(
  'одиночные цифры не значимы: «3 объекта» vs «7 объектов»',
  numericVeto('Целью было 3 объекта', 'Целью было 7 объектов') === false
);
check(
  'одинаковые числа не ветируют: «Brent выше $90» vs «Brent выше $90»',
  numericVeto('Нефть Brent подорожала выше $90', 'Нефть Brent подорожала выше $90') === false
);
check(
  'пересечение чисел есть: «85 дронов» vs «сбили 85 и 130 дронов» — не вето',
  numericVeto('Сбито 85 дронов', 'Сбито 85 и 130 дронов') === false
);
check(
  'число только у одной стороны — вето невозможно',
  numericVeto('Сбито 516 дронов', 'ВКС отразили массированную атаку') === false
);

// ═══════════════════════════════════════════════════════════════════════════
// 2. significantNumbers
// ═══════════════════════════════════════════════════════════════════════════
console.log('\n[significantNumbers]');
check('двузначные числа значимы', significantNumbers('Сбито 85 дронов').has('85'));
check('год 2025 не значим', !significantNumbers('Итоги 2025 года').has('2025'));
check('год 2026 не значим', !significantNumbers('Прогноз на 2026 год').has('2026'));
check('одиночная цифра не значима', !significantNumbers('Топ-5 новостей').has('5'));
check('длинные числа значимы', significantNumbers('Курс нефти превысил $10000').has('10000'));

// ═══════════════════════════════════════════════════════════════════════════
// 3. isRubricTitle
// ═══════════════════════════════════════════════════════════════════════════
console.log('\n[isRubricTitle]');
check(
  'дайджест после обрезки эмодзи: «📊 Курсы валют на 12 сентября»',
  isRubricTitle('📊 Курсы валют на 12 сентября') === true
);
check('«Что случилось этой ночью» — рубрика', isRubricTitle('Что случилось этой ночью') === true);
check('«Итоги торгов» — рубрика', isRubricTitle('Итоги торгов на Мосбирже') === true);
check(
  'обычный заголовок — не рубрика',
  isRubricTitle('Сбер отчитался о рекордной прибыли по РСБУ') === false
);

// ═══════════════════════════════════════════════════════════════════════════
// Итог
// ═══════════════════════════════════════════════════════════════════════════
console.log(`\nИтог: ${passed} прошло, ${failed} упало`);
if (failed > 0) {
  console.log('Падения:', failures.join('; '));
  process.exit(1);
}
console.log('verify:clusteringVeto — OK');
