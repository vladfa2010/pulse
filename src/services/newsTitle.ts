/**
 * =============================================================================
 * PULSE — Санитайзер заголовков новостей (ТЗ-222)
 * =============================================================================
 *
 * Очистка presentation-заголовков от мусора источников: эмодзи-флагов,
 * #хэштегов, markdown-выделения/заголовков. Применяется в точке формирования
 * top_news карточек бакетов и в промпте LLM — НЕ трогает колонки БД
 * (title_ru/title_original), живую ленту и NewsCard.
 *
 * Регламент: Unicode-классы (\p{L}\p{N}) с u-флагом обязательны — \w ASCII-only
 * и ест кириллицу (тот же урок, что f325898 / \W-фикс ТЗ-163).
 */

/**
 * Санитайз заголовка. null in → null out (контракт nullable-полей).
 * Порядок правил важен (прогнан на живых русских образцах 22.11):
 *  1. эмодзи-флаги (пара regional indicators = один флаг);
 *  2. #хэштеги (только начинающиеся с границы слова);
 *  3. markdown-выделение *…* / _…_;
 *  4. markdown-заголовки ## …;
 *  5. схлопывание пробелов + trim.
 */
export function sanitizeNewsTitle(t: string | null): string | null {
  if (t == null) return null;
  let out = t;
  // 1. эмодзи-флаги: два regional indicator подряд — один флаг
  out = out.replace(/[\u{1F1E6}-\u{1F1FF}]{2}/gu, '');
  // 2. хэштеги (граница слова; \p{L}\p{N}_ — Unicode)
  out = out.replace(/(^|\s)#[\p{L}\p{N}_]+/gu, '$1');
  // 3. markdown-выделение: **жирный**, *курсив*, __жирный__, _курсив_
  //    (рекурсивно — для случаев вида «***»/«* * *»)
  out = out.replace(/\*{1,3}([^*]+)\*{1,3}/gu, '$1');
  out = out.replace(/\*{1,3}([^*]+)\*{1,3}/gu, '$1');
  out = out.replace(/_{1,3}([^_]+)_{1,3}/gu, '$1');
  out = out.replace(/_{1,3}([^_]+)_{1,3}/gu, '$1');
  // 4. markdown-заголовки: «## Слово» → «Слово» (# уже убран хэштег-правилом,
  //    если шёл от границы слова — здесь страховка для «##» сразу после текста)
  out = out.replace(/(^|\s)#{1,6}\s*([\p{L}\p{N}])/gu, '$1$2');
  // 4а. оставшиеся маркеры без содержимого («***», «##») — удалить целиком
  out = out.replace(/[*_#]+/gu, ' ');
  // 5. схлопнуть пробелы
  out = out.replace(/\s{2,}/g, ' ').trim();
  return out;
}
